export const maknoonCopy = Object.freeze(Object.fromEntries(
  revisions.map(([id, previous, revised]) => [id, Object.freeze({ previous, revised })])
));

export function refineMaknoonDescription(product) {
  const revision = maknoonCopy[product.id];
  if (!revision || product.description !== revision.previous) return product;
  return { ...product, description: revision.revised };
}
